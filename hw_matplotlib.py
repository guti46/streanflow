"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

import matplotlib.pyplot as plt
import numpy as np

# chart info
L = 6
RA = 170
RB = 410
P1 = 100

q1 = 120
q2 = 120

# beam points
x = np.linspace(0, L, 500)
V = np.zeros_like(x)

# calculations
for i in range(len(x)):

    if x[i] < 2:
        V[i] = RA - q1 * x[i]


    elif x[i] < 4:
        V[i] = RA - q1 * 2 - P1

    else:
        V[i] = RA - q1 * 2 - P1 + RB - q2 * (x[i] - 4)

# graph it
plt.plot(x, V)
plt.fill_between(x, V, 0, alpha=0.3)

# label it
plt.title("Shear Diagram")


plt.xlabel("x (ft)")
plt.ylabel("V (lb)")
plt.axhline(0, color="black")
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

import matplotlib.pyplot as plt
import numpy as np

# info
L = 6
RA = 170
RB = 410
P1 = 100
q1 = 120
q2 = 120

# points on beam
x = np.linspace(0, L, 500)
M = np.zeros_like(x)


# calculate points
for i in range(len(x)):
    if x[i] < 2:
        M[i] = RA * x[i] - q1 * (x[i]**2 / 2)



    elif x[i] < 4:
        M[i] = RA * x[i] - q1 * 2 * (x[i] - 1) - P1 * (x[i] - 2)

    else:
        M[i] = RA * x[i] - q1 * 2 * (x[i] - 1) - P1 * (x[i] - 2) + RB * (x[i] - 4) - q2 * (x[i] - 4)**2 / 2

# graph
plt.plot(x, M)
plt.fill_between(x, M, 0, alpha=0.3)

# labels for graph
plt.title("Moment Diagram")
plt.xlabel("x (ft)")

plt.ylabel("M (lb-ft)")
plt.axhline(0, color="black")
plt.show()

